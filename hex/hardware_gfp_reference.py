def main():
    script_dir = get_script_dir()

    # Parse command-line arguments
    parser = argparse.ArgumentParser(
        description='Generate HARDWARE-ACCURATE GFP GEMM golden reference',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
This script generates golden references using the HARDWARE-ACCURATE algorithm
that matches the RTL implementation. It also computes EMULATOR-BASED and
FLOATING-POINT references for comparison.

Output files:
  golden_B{B}_C{C}_V{V}.hex     - HARDWARE-ACCURATE reference (use this!)
  golden_B{B}_C{C}_V{V}_emu_NEW.hex - Emulator-based (for comparison)
  out.hex                       - Same as hardware-accurate reference
        """
    )
    parser.add_argument('--B', type=int, default=128, help='Output rows (batch size)')
    parser.add_argument('--C', type=int, default=128, help='Output columns')
    parser.add_argument('--V', type=int, default=1, help='Inner dimension multiplier (V Native Vectors)')
    parser.add_argument('--left', type=str, default=None, help='Path to left matrix hex file')
    parser.add_argument('--right', type=str, default=None, help='Path to right matrix hex file')
    parser.add_argument('--output', type=str, default=None, help='Path to output golden hex file')
    args = parser.parse_args()

    B, C, V = args.B, args.C, args.V

    # Validate parameters
    if B * V > 128 or C * V > 128:
        print(f"ERROR: Invalid parameters! BxV={B*V} and CxV={C*V} must both be <= 128")
        sys.exit(1)

    # Set default file paths
    left_hex_path = args.left if args.left else os.path.join(script_dir, 'left.hex')
    right_hex_path = args.right if args.right else os.path.join(script_dir, 'right.hex')
    output_path = args.output if args.output else os.path.join(script_dir, f'golden_B{B}_C{C}_V{V}.hex')

    print("=" * 80)
    print("HARDWARE-ACCURATE GFP GEMM Reference Generation")
    print("=" * 80)
    print(f"\nConfiguration: B={B}, C={C}, V={V}")
    print(f"  Matrix A: {B} x {128*V} (uses {B*V} Native Vectors)")
    print(f"  Matrix B: {128*V} x {C} (uses {C*V} Native Vectors)")
    print(f"  Output:   {B} x {C} = {B*C} results")

    # Load matrices
    print("\n1. Loading matrices from hex files...")
    print(f"   Left matrix: {left_hex_path}")
    print(f"   Right matrix: {right_hex_path}")

    exp_left_raw, man_left_raw = load_hex_file(left_hex_path)
    left_exp_torch = decode_exponents(exp_left_raw)
    left_exp = left_exp_torch.numpy()
    left_mant = decode_mantissas(man_left_raw)

    exp_right_raw, man_right_raw = load_hex_file(right_hex_path)
    right_exp_torch = decode_exponents(exp_right_raw)
    right_exp = right_exp_torch.numpy()
    right_mant = decode_mantissas(man_right_raw)

    print(f"   Left matrix: {left_mant.shape}, exponents: {left_exp.shape}")
    print(f"   Right matrix: {right_mant.shape}, exponents: {right_exp.shape}")

    # Compute results using all three methods
    results_hardware = None
    results_emulator = None
    results_fp = None

    # 1. HARDWARE-ACCURATE (primary)
    print("\n2. Computing with HARDWARE-ACCURATE Algorithm (for golden generation)...")
    hw_compute = HardwareGFPCompute(exp_bits=5, exp_bias=15, group_size=32)
    results_hardware = hw_compute.compute_gemm_with_bcv(left_mant, left_exp, right_mant, right_exp, B, C, V)
    print(f"   [HARDWARE] Generated {len(results_hardware)} FP16 results ({B}x{C})")
    print(f"   [HARDWARE] First 4 values: {' '.join(f'0x{v:04x}' for v in results_hardware[:4])}")

    # 2. EMULATOR-BASED (for comparison)
    print("\n3. Computing with EMULATOR Algorithm (for comparison only)...")
    results_emulator = compute_emulator_golden(B, C, V, left_mant, left_exp, right_mant, right_exp)

    # 3. FLOATING-POINT (for comparison)
    print("\n4. Computing with FLOATING-POINT Reference (for comparison)...")
    results_fp = compute_fp_reference(left_mant, left_exp, right_mant, right_exp, B, C, V)

    # Compare all three methods
    print("\n" + "=" * 80)
    print("COMPARISON: Hardware vs Emulator vs Floating-Point")
    print("=" * 80)

    def compare_results(name1, results1, name2, results2):
        """Compare two result arrays and print metrics."""
        if results1 is None or results2 is None:
            print(f"   Cannot compare: {name1 if results1 is None else name2} not available")
            return

        # Convert to float
        float1 = np.array([np.frombuffer(struct.pack('<H', v), dtype=np.float16)[0] for v in results1], dtype=np.float32)
        float2 = np.array([np.frombuffer(struct.pack('<H', v), dtype=np.float16)[0] for v in results2], dtype=np.float32)

        # Compute metrics
        exact_matches = np.sum(results1 == results2)
        total = len(results1)
        match_rate = 100.0 * exact_matches / total

        abs_errors = np.abs(float1 - float2)
        rmse = np.sqrt(np.mean((float1 - float2)**2))
        max_error = np.max(abs_errors)
        mean_error = np.mean(abs_errors)

        print(f"\n{name1} vs {name2}:")
        print(f"  Exact FP16 matches: {exact_matches}/{total} ({match_rate:.1f}%)")
        print(f"  RMSE:               {rmse:.6e}")
        print(f"  Max absolute error: {max_error:.6e}")
        print(f"  Mean absolute error: {mean_error:.6e}")

    compare_results("HARDWARE", results_hardware, "EMULATOR", results_emulator)
    compare_results("HARDWARE", results_hardware, "FP-REF", results_fp)
    compare_results("EMULATOR", results_emulator, "FP-REF", results_fp)

    # Write output files
    print("\n" + "=" * 80)
    print("5. Writing output files...")

    # HARDWARE-ACCURATE golden (primary output)
    print(f"   Writing HARDWARE-ACCURATE golden to {output_path}...")
    with open(output_path, 'w') as f:
        for val in results_hardware:
            f.write(f"{val:04x}\n")
    print(f"   [OK] Wrote {len(results_hardware)} values")

    # Also write to out.hex for backward compatibility
    if args.output is None:
        out_path = os.path.join(script_dir, 'out.hex')
        print(f"   Writing to {out_path}...")
        with open(out_path, 'w') as f:
            for val in results_hardware:
                f.write(f"{val:04x}\n")
        print(f"   [OK] Wrote {len(results_hardware)} values")

    # EMULATOR golden (for comparison)
    if results_emulator is not None:
        emu_path = os.path.join(script_dir, f'golden_B{B}_C{C}_V{V}_emu.hex')
        print(f"   Writing EMULATOR reference to {emu_path}...")
        with open(emu_path, 'w') as f:
            for val in results_emulator:
                f.write(f"{val:04x}\n")
        print(f"   [OK] Wrote {len(results_emulator)} values")

    # Verification
    print(f"\n6. Verification (first 16 HARDWARE-ACCURATE results):")
    num_to_show = min(16, len(results_hardware))
    for i in range(num_to_show):
        row = i // C
        col = i % C
        fp16_bits = results_hardware[i]
        fp16_val = np.frombuffer(struct.pack('<H', fp16_bits), dtype=np.float16)[0]
        print(f"   [{i:2d}] output[{row},{col}] = 0x{fp16_bits:04x} ({fp16_val:8.4f})")

    print("\n" + "=" * 80)
    print("Golden reference generation complete!")
    print("\nFiles generated:")
    print(f"  {output_path} - HARDWARE-ACCURATE reference (USE THIS FOR RTL VERIFICATION)")
    if args.output is None:
        print(f"  out.hex - Same as hardware-accurate reference")
    if results_emulator is not None:
        print(f"  golden_B{B}_C{C}_V{V}_emu.hex - Emulator reference (for comparison)")
    print("=" * 80)


