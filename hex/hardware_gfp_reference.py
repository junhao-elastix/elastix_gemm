#!/usr/bin/env python3
"""
Hardware-Accurate GFP GEMM Reference Model

===============================================================================
PURPOSE
===============================================================================
This script generates golden references for GFP GEMM hardware verification.
It implements TWO algorithms for comparison:

1. HARDWARE-ACCURATE ALGORITHM (HardwareGFPCompute class):
   - Matches RTL implementation exactly (compute_engine.sv, gfp8_nv_dot.sv)
   - Used for generating golden reference files
   - This is the PRIMARY algorithm for hardware verification

2. EMULATOR-BASED ALGORITHM (compute_emulator_golden function):
   - Uses the GFP emulator library (group_floating_point.py)
   - May have slight differences from hardware due to implementation details
   - Used for COMPARISON ONLY, not for golden generation

===============================================================================
OUTPUTS
===============================================================================
- golden_B{B}_C{C}_V{V}.hex: HARDWARE-ACCURATE reference (matches RTL)
- golden_B{B}_C{C}_V{V}_emu_NEW.hex: Emulator-based reference (for comparison)
- out.hex: Same as hardware-accurate reference
- Comprehensive comparison metrics (RMSE, max error, match rate)

===============================================================================
HARDWARE-ACCURATE ALGORITHM (from compute_engine.sv)
===============================================================================
For each output element C[i,j]:
  1. Compute 4 group dot products (integer multiply-accumulate)
  2. Align mantissas by maximum exponent across groups
  3. Sum aligned mantissas as integers
  4. Convert GFP result to FP16 with IEEE 754 rounding

V-LOOP ACCUMULATION (matching gfp8_bcv_controller.sv):
For each output element C[i,j] with V Native Vectors:
  1. Compute V dot products (one per Native Vector)
  2. INCREMENTAL ACCUMULATION (pairwise max-align-sum):
     - For v=0: Initialize accumulator with first dot product
     - For v>0: Find max between accumulator and current dot product
     - Align both mantissas to max exponent
     - Sum aligned mantissas and update accumulator
  3. Convert final GFP result to FP16

===============================================================================
USAGE
===============================================================================
  python hardware_gfp_reference_new.py --B 4 --C 4 --V 4

Loads matrices from left.hex and right.hex (generated by generate_nv_hex.py).
"""

