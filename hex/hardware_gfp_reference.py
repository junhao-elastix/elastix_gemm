def compute_fp_reference(left_mant, left_exp, right_mant, right_exp, B, C, V, exp_bias=15):
    """
    Compute floating-point reference for comparison.

    This dequantizes the GFP matrices to float and performs standard FP matmul.

    Args:
        left_mant: [128, 128] left mantissa matrix
        left_exp: [128, 4] left exponent matrix
        right_mant: [128, 128] right mantissa matrix
        right_exp: [128, 4] right exponent matrix
        B, C, V: Matrix dimension parameters
        exp_bias: Exponent bias (default: 15)

    Returns:
        np.array: FP16 results as uint16 array
    """
    print(f"\n   [FP-REF] Computing floating-point reference...")

    # Convert GFP to float
    def gfp_to_float(mant_matrix, exp_matrix):
        rows, cols = mant_matrix.shape
        float_matrix = np.zeros((rows, cols), dtype=np.float64)
        for r in range(rows):
            for c in range(cols):
                group_idx = c // 32
                exp_val = int(exp_matrix[r, group_idx])
                mant_val = int(mant_matrix[r, c])
                if exp_val == 0:
                    float_matrix[r, c] = 0.0
                else:
                    scale = 2.0 ** (exp_val - exp_bias)
                    float_matrix[r, c] = mant_val * scale
        return float_matrix

    left_float = gfp_to_float(left_mant, left_exp)
    right_float = gfp_to_float(right_mant, right_exp)

    # Extract submatrices
    left_sub = left_float[:B*V, :]  # (B*V) x 128
    right_sub = right_float[:C*V, :]  # (C*V) x 128

    # Perform float matmul with V-loop accumulation
    result = np.zeros((B, C), dtype=np.float64)
    for b in range(B):
        for c in range(C):
            for v in range(V):
                left_vec = left_sub[b*V + v, :]  # 128 elements
                right_vec = right_sub[c*V + v, :]  # 128 elements
                result[b, c] += np.dot(left_vec, right_vec)

    # Convert to FP16
    result_fp16 = result.astype(np.float16).flatten()
    results_fp = np.array([np.frombuffer(val.tobytes(), dtype=np.uint16)[0] for val in result_fp16], dtype=np.uint16)

    print(f"   [FP-REF] Generated {len(results_fp)} FP16 results ({B}x{C})")
    print(f"   [FP-REF] First 4 values: {' '.join(f'0x{v:04x}' for v in results_fp[:min(4, len(results_fp))])}")

    return results_fp


